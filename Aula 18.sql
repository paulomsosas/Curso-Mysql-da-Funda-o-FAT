-- LISTAR PRODUTO DISPONÍVEIS COM QUANTAS X FORAM VENDIDOS

SELECT * FROM PRODUTOS18;
SELECT * FROM VENDAS18;

SELECT PROD_NOME AS PRODUTO,VEN_IDVENDA AS VENDA,VEN_QUANT AS QUANT,VEN_DATAVENDA AS DATA FROM PRODUTOS18 AS PRO
	LEFT JOIN 
VENDAS18 AS VEN ON PRO.PROD_ID=VEN.VEN_IDPRODUTO
	ORDER BY
PROD_NOME;


--- CLASSIFICAR PRODUTO PRO FAIXA

SELECT PROD_NOME AS PRODUTO,PROD_PRECO AS VALOR,FX_DESCRICAO AS DESCRIÇÃO FROM PRODUTOS18 AS PRO
	JOIN
FAIXA_PRECO18 AS FAIXA ON PRO.PROD_PRECO BETWEEN FAIXA.FX_PRECO_MIN AND FAIXA.FX_PRECO_MAX
	ORDER BY
PROD_PRECO;

